// Vamos falar de vetores agora!
// Vetores são estruturas de dados que armazenam elementos do mesmo tipo em uma sequência contígua na memória. 
// Eles permitem acesso rápido aos elementos através de índices, o que os torna muito eficientes para certas operações.
// Veja um exmeplo de aplicação de vetores em C++:

#include <iostream>
using namespace std;
int main () {
    // Declarando um vetor de inteiros com 5 elementos
    int numeros[5];
 return 0;
}
// Acima , declaramos um vetor de inteiros chamado "numeros" com 5 elementos.

// Diferente de python, em C++ precisamos declarar o tamanho do vetor no momento da sua criação.
// Outra diferença importante é que os vetores em C++ têm tamanho fixo, ou seja, uma vez criado, o tamanho do vetor não pode ser alterado.
// Um vetor também só se refere a um tipo de dado, ou seja, todos os elementos do vetor devem ser do mesmo tipo.

